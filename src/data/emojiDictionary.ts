/**
 * Common Turkish and English suffixes to strip when looking up stems
 */
const TURKISH_SUFFIX_REGEX =
  /(?:larımızdan|lerimizden|larımızda|lerimizde|larımıza|lerimize|larımızı|lerimizi|larımız|lerimiz|larından|lerinden|larında|lerinde|larına|lerine|larını|lerini|ların|lerin|ları|leri|lığın|liğin|luğun|lüğün|lığa|liğe|lığım|liğim|lık|lik|luk|lük|ümün|imin|ımın|unun|ünün|ümüz|imiz|ımız|umuz|ünüz|iniz|ınız|unuz|eyim|ayım|elim|alım|iyorum|uyorsun|ıyorum|üyorum|iyorsun|ıyorsun|üyorsun|iyor|uyor|üyor|ıyor|yordu|diler|tiler|dular|tular|düm|dim|dım|dum|tüm|tim|tım|tum|dün|din|dın|dun|tün|tin|tın|tun|miş|mış|muş|müş|den|dan|ten|tan|de|da|te|ta|ler|lar|mez|maz|yor|ken|siz|sız|suz|süz|sin|sın|sun|sün|yim|yım|yum|yüm|ar|er|ır|ir|ur|ür|im|ım|um|üm|in|ın|un|ün|le|la|yle|yla|ye|ya|ne|na|ni|nı|nu|nü|e|a|i|ı|u|ü)$/i;

const ENGLISH_SUFFIX_REGEX = /(?:ing|ed|s|es|er|est|ly|ness|ment|ful|less|'s|'re|'ve|'ll|'d)$/i;

/**
 * Consonant softening reversal in Turkish (p->b, t->d, k->ğ, ç->c)
 */
const CONSONANT_REPLACEMENTS: Record<string, string> = {
  b: 'p',
  d: 't',
  c: 'ç',
  ğ: 'k',
};

/**
 * High-accuracy lyric word-to-emoji resolver.
 * Handles Turkish agglutinative suffixes, English morphology,
 * and semantic lyric roots (distinguishing "gül/güller" 🌹 from "gülmek/gülüyor" 😊).
 */
export function getEmojiForWord(rawWord: string): string | undefined {
  if (!rawWord) return undefined;

  // Clean punctuation and lowercase
  const cleaned = rawWord
    .toLowerCase()
    .replace(/[^a-z0-9ğüşıöç]/gi, '')
    .trim();

  if (!cleaned || cleaned.length < 2) return undefined;

  // 1. Direct full-word match (handles "güller" -> 🌹, "gülüyor" -> 😊, etc.)
  if (EMOJI_MAP[cleaned]) {
    return EMOJI_MAP[cleaned];
  }

  // Special check for "gül-" verb forms not explicitly listed (güldükçe, gülünce, gülerken, etc.)
  if (
    /^gül(?:mek|üyor|dü|dük|dün|düm|er|en|üş|ümse|ünce|erken)/.test(cleaned)
  ) {
    return '😊';
  }

  // 2. Turkish stemming: Iteratively strip suffixes down to 2 letters
  let stem = cleaned;
  for (let pass = 0; pass < 2; pass++) {
    const stripped = stem.replace(TURKISH_SUFFIX_REGEX, '');
    if (stripped && stripped.length >= 2 && stripped !== stem) {
      if (EMOJI_MAP[stripped]) {
        return EMOJI_MAP[stripped];
      }
      // Test consonant softening (kalb -> kalp, derd -> dert, reng -> renk, etc.)
      const lastChar = stripped.slice(-1);
      if (CONSONANT_REPLACEMENTS[lastChar]) {
        const softened = stripped.slice(0, -1) + CONSONANT_REPLACEMENTS[lastChar];
        if (EMOJI_MAP[softened]) {
          return EMOJI_MAP[softened];
        }
      }
      stem = stripped;
    }
  }

  // 3. English stemming
  const engStripped = cleaned.replace(ENGLISH_SUFFIX_REGEX, '');
  if (engStripped && engStripped.length >= 3 && engStripped !== cleaned) {
    if (EMOJI_MAP[engStripped]) {
      return EMOJI_MAP[engStripped];
    }
  }

  // 4. Hyphenated / repeated words (e.g. "amatör-tör-tör" -> check first part "amatör")
  if (rawWord.includes('-')) {
    const firstPart = rawWord
      .split('-')[0]
      .toLowerCase()
      .replace(/[^a-z0-9ğüşıöç]/gi, '')
      .trim();
    if (firstPart && firstPart.length >= 2 && firstPart !== cleaned) {
      return getEmojiForWord(firstPart);
    }
  }

  return undefined;
}
